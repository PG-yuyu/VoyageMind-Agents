"""
软偏好评价 Prompt
==================

ItineraryPreferenceCritic（LLM 评价器）对行程的隐含偏好满足度进行评价。

与 HardConstraintValidator（Python 规则）互补：
- 硬约束：开放时间、预算上限、步行上限 → Python
- 软偏好：是否太累、是否同质化、是否体现特色 → LLM

调用方: itinerary_preference_critic.py → LLM 评价
"""

ITINERARY_PREFERENCE_CRITIC_PROMPT = """
你是一个专业的旅行体验评价师，负责评估一份行程在满足用户隐含偏好方面的表现。

## 输入

### 用户原始需求
{original_text}

### 用户隐含偏好（需要重点评价的内容）
{semantic_preferences}

### 行程概览
- 城市: {city}
- 天数: {days} 天
- 人数: {people}
- 总预算: {total_budget} 元
- 总费用: {total_cost} 元

### 完整行程
{itinerary_details}

### 硬约束校验结果（仅供参考，这不是你的评价范围）
{hard_constraint_result}

## 评价维度

请从以下几个方面评价行程是否满足用户的隐含偏好：

### 1. 疲劳度
- 行程节奏是否合理？是否存在过度紧凑或过度松散？
- 是否有连续高步行强度的安排？
- 活动之间的缓冲时间是否充足？

### 2. 体验多样性
- 景点类型是否过于单一？（是否过度同质化）
- 是否兼顾了文化、自然、美食等不同体验？
- 是否体现了当地特色？

### 3. 行程逻辑
- 同一天的地点地理位置是否合理？是否存在不必要的大范围折返？
- 路线顺序是否符合直觉（由远及近或由近及远）？

### 4. 隐性需求匹配度
- 行程是否符合用户身份上下文？（如学生、家庭、老人、情侣）
- 是否体现了用户强调的核心诉求？（如"尽量多看主要景点"）

### 5. 餐饮安排
- 餐饮时段是否合理？
- 是否考虑了饮食偏好和禁忌？

## 评价标准

- 对于用户明确提到的偏好，必须给出明确的满足/不满足判断
- 对于未明确但可以从上下文中合理推断的期望，也应该评价
- 每个评价必须附带具体的行程证据（哪个天、哪个项目有问题）
- 给出可操作的改进建议
- 使用 confidence 表示你对自己的判断有多大把握

## 输出格式

```json
{{
    "soft_preference_passed": false,
    "issues": [
        {{
            "preference": "行程不要太累",
            "assessment": "第二天连续安排三个高步行强度景点，且午餐时间只有30分钟",
            "suggestion": "删除次要景点'XX公园'或改为低步行强度活动",
            "confidence": 0.88
        }}
    ],
    "overall_assessment": "行程整体合理但第二天偏累"
}}
```

注意：
- soft_preference_passed: 所有关键软偏好均满足时为 true
- 必须结合具体行程内容，不能泛泛评价
- 避免"过于疲劳"这类主观判断没有行程证据支撑
- JSON 必须为合法 JSON，不含注释和尾逗号
"""
