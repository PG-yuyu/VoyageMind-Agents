SOFT_PREFERENCE_OPTIMIZATION_PROMPT = """
你是一个智能行程优化助手。上一轮生成的行程在隐含偏好方面存在不足，
请根据软偏好评价对行程进行优化。

## 原始行程
{current_itinerary}

## 软偏好评价结果
{preference_evaluation}

## 候选资源（同上一轮）
{places}

## 优化要求

### 核心原则
1. **保留整体框架**：不要大改行程结构，只优化有问题的部分
2. **精准优化**：针对每个评价建议做有针对性的调整
3. **不影响硬约束**：优化后不得引入新的硬约束违规
4. **使用已有资源**：使用候选资源中已有的 place_id

### 常见优化策略

| 优化目标 | 推荐策略 |
|---------|---------|
| 降低疲劳度 | 减少连续高强度景点，增加休息/缓冲时间 |
| 增加多样性 | 替换同质化景点为不同类型景点 |
| 改善路线逻辑 | 调整景点顺序减少折返 |
| 匹配用户身份 | 根据学生/家庭/老人上下文调整节奏和选择 |
| 提升体验 | 增加当地特色体验或文化元素 |

### 不用优化的情况
- 如果软偏好评价认为没有问题（soft_preference_passed=true），直接返回原始行程
- 如果评价建议不明确或 confidence 低，可以提出质疑

## 输出格式

```json
{{
    "days": [
        {{
            "day": 1,
            "items": []
        }}
    ],
    "optimization_notes": [
        "为缓解 X 问题，增加了 15 分钟缓冲时间",
        "将 Y 替换为 Z 以增加景点多样性"
    ],
    "preference_improvements": [
        "疲劳度: 第二天从 3 个景点减为 2 个"
    ]
}}
```

注意：
- 必须输出完整行程 JSON
- optimization_notes 记录每项优化及其目标
- preference_improvements 记录每个维度的改善情况
- JSON 必须为合法 JSON，不含注释和尾逗号
"""
